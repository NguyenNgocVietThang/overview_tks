'use strict';
// Dựng dữ liệu giả từ file kiểm kê: vị trí hàng HN + các đơn có SL sát tổng tồn của mã.
// Chạy: node prototype-kiemke-demo.cjs "<đường dẫn kiểm kê.xlsx>" → public/prototypes/order-picking/kiem-ke-demo.js
const fs = require('node:fs'), path = require('node:path'), XLSX = require('xlsx');
const S = require('./public/prototypes/order-picking/stocktake.js');

const source = process.argv[2];
if (!source) { console.error('Thiếu đường dẫn file kiểm kê .xlsx'); process.exit(1); }
const wb = XLSX.readFile(source);
const rows = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { header:1, defval:'' })
  .map(r => r.slice(0, 5)).filter(r => r.some(c => String(c).trim() !== ''));
const built = S.build(rows, { branch:'HN' });

const byCode = new Map();
for (const line of built.lines) {
  const entry = byCode.get(line.codeKey) || { code:line.code, name:line.name, spec:line.spec, total:0, locations:[] };
  entry.total += line.quantity;
  entry.locations.push(line);
  byCode.set(line.codeKey, entry);
}

// Số ngẫu nhiên có hạt giống cố định để chạy lại ra đúng dữ liệu cũ.
let seed = 20261026;
const random = () => (seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296;

const candidates = [...byCode.values()]
  .filter(p => Number.isInteger(p.total) && p.total >= 30 && p.total <= 3000 && p.locations.length >= 2 && p.name)
  .sort((a, b) => a.code.localeCompare(b.code));
for (let i = candidates.length - 1; i > 0; i--) { const j = Math.floor(random() * (i + 1)); [candidates[i], candidates[j]] = [candidates[j], candidates[i]]; }

const customers = ['Gia dụng Thanh Xuân', 'Siêu thị Cầu Giấy', 'Cửa hàng Tây Hồ', 'Tạp hóa Đống Đa', 'Gia dụng Hai Bà Trưng', 'Siêu thị Nam Từ Liêm', 'Cửa hàng Gia Lâm', 'Gia dụng Hoài Đức', 'Tạp hóa Thanh Trì', 'Siêu thị Mê Linh'];
const sales = ['Nguyễn Hà', 'Trần Linh', 'Phạm Quân'];
const ratios = [1, 0.98, 0.95, 0.92, 0.9, 0.97];   // 1 = đơn lấy đúng toàn bộ tồn của mã
const LINES_PER_ORDER = 6;

const orders = customers.map((customer, i) => ({
  branch:'HN', orderCode:'DH-KK-' + String(i + 1).padStart(3, '0'),
  customerName:customer + ' · mô phỏng', saleName:sales[i % sales.length],
  status:{ code:'SENT_TO_ACCOUNTANT', label:'Đơn đã gửi kế toán' }, invoiceDiscount:0, priorDebt:0,
  note:'Dữ liệu thử dựng từ file kiểm kê: SL mỗi dòng bằng 90–100% tổng tồn của mã.',
  lines:candidates.slice(i * LINES_PER_ORDER, (i + 1) * LINES_PER_ORDER).map((p, j) => ({
    productCode:p.code, productName:p.name,
    quantity:Math.max(1, Math.floor(p.total * ratios[(i + j) % ratios.length])),
    price:Math.round((4000 + random() * 76000) / 100) * 100, note:p.spec || ''
  }))
}));

// Cùng số liệu với file kiểm kê để chạy được cả khi chưa bấm "Nạp làm tồn đầu"; ngày về trước giờ chốt 26/10.
const locations = built.lines.map(l => ({ branch:'HN', code:l.code, location:l.location, available:l.quantity, notes:l.spec || '', arrivalDate:'20/10/2026' }));

const output = path.join(__dirname, 'public/prototypes/order-picking/kiem-ke-demo.js');
fs.writeFileSync(output, '/* GENERATED by server/prototype-kiemke-demo.cjs từ file kiểm kê. Không sửa tay. */\n(function(){\n  const data = '
  + JSON.stringify({ orders, locations }) + ';\n  window.PickingDemo.orders.push(...data.orders);\n  window.PickingDemo.locations.push(...data.locations);\n})();\n');
console.log('orders', orders.length, 'lines', orders.reduce((s, o) => s + o.lines.length, 0), 'locations', locations.length, '·', Math.round(fs.statSync(output).size / 1024) + ' KB');
for (const o of orders.slice(0, 2)) console.log(o.orderCode, o.lines.map(l => l.productCode + ' ' + l.quantity + '/' + byCode.get(S.codeKey(l.productCode)).total).join(' | '));
